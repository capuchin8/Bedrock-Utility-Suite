/**
 * Resolves an item typeId (e.g. "minecraft:diamond_sword") to a resource
 * pack texture path suitable for ActionFormData.button()'s icon param.
 * Returns an empty string if unresolved (caller should treat that as "no icon").
 *
 * Priority: admin-set override (persisted, per-item) > hardcoded override >
 * generated vanilla map.
 */
export function resolveItemIcon(typeId: string): string {
  const shortId = typeId.includes(":") ? typeId.split(":")[1] : typeId;

  const adminOverride = getIconOverride(typeId);
  if (adminOverride) return adminOverride;

  if (BUS_ITEM_ICON_OVERRIDES[typeId]) return BUS_ITEM_ICON_OVERRIDES[typeId];
  if (BUS_3D_BLOCK_ICONS[shortId]) return BUS_3D_BLOCK_ICONS[shortId];
  if (BUS_SPAWN_EGG_ICONS[shortId]) return BUS_SPAWN_EGG_ICONS[shortId];
  if (BUS_ITEM_ICON_MAP[shortId]) return BUS_ITEM_ICON_MAP[shortId];

  return "";
}
